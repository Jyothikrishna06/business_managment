import test from 'node:test';
import assert from 'node:assert/strict';
import {mkdtempSync,rmSync} from 'node:fs';
import {tmpdir} from 'node:os';
import {join,resolve,sep} from 'node:path';
import {once} from 'node:events';

test('accounts, authorization, billing, payments and password recovery',async t=>{
  const dir=mkdtempSync(join(tmpdir(),'subscript-test-'));
  const port=13000+Math.floor(Math.random()*10000);
  Object.assign(process.env,{PORT:String(port),APP_URL:`http://localhost:${port}`,DATA_DIR:dir,DEV_RESET_LINKS:'true',SMTP_HOST:''});
  let output='';const originalLog=console.log;
  console.log=(...args)=>{output+=args.join(' ')+'\n';};
  const {server}=await import('../server.js');
  if(!server.listening)await once(server,'listening');
  t.after(async()=>{await new Promise(resolve=>server.close(resolve));console.log=originalLog;const p=resolve(dir);if(p.startsWith(resolve(tmpdir())+sep)&&p.includes('subscript-test-'))rmSync(p,{recursive:true,force:true});});
  const call=async(path,method='GET',body,cookie)=>{const r=await fetch(`http://127.0.0.1:${port}/api${path}`,{method,headers:{'Content-Type':'application/json',...(cookie?{cookie}:{})},body:body?JSON.stringify(body):undefined});return {status:r.status,body:await r.json(),cookie:r.headers.get('set-cookie')?.split(';')[0]};};
  const admin={email:'make_a_ton@gmail.com',password:'makeaton123'};
  assert.equal((await call('/state')).status,401);
  assert.equal((await call('/auth/register','POST',{name:'Weak User',email:'weak@example.com',password:'weak'})).status,400);
  assert.equal((await call('/auth/register','POST',{name:'Imposter',...admin})).status,400);
  assert.equal((await call('/auth/login','POST',{...admin,password:'wrong'})).status,401);
  const login=await call('/auth/login','POST',admin);assert.equal(login.body.user.role,'admin');const cookie=login.cookie;
  const create=async(type,b)=>{const r=await call(`/records/${type}`,'POST',b,cookie);assert.equal(r.status,200,JSON.stringify(r.body));return r.body;};
  const product=await create('products',{name:'Software seat',price:50,cost:10});
  const plan=await create('plans',{name:'Monthly',cycle:'Monthly',minQuantity:1});
  const customer=await create('customers',{name:'Customer One',email:'one@example.com'});
  const second=await create('customers',{name:'Customer Two',email:'two@example.com'});
  const discount=await create('discounts',{name:'Launch',kind:'Percentage',value:10,minQuantity:1,limit:1});
  const tax=await create('taxes',{name:'Sales tax',rate:10});
  const today=new Date().toISOString().slice(0,10);
  const sub=await create('subscriptions',{number:'SUB-TEST',customerId:customer.id,productId:product.id,planId:plan.id,quantity:2,unitPrice:50,starts:today,status:'Active',discountId:discount.id,taxId:tax.id});
  assert.equal((await call('/billing','POST',{},cookie)).body.count,1);
  assert.equal((await call('/billing','POST',{},cookie)).body.count,0);
  let state=(await call('/state','GET',null,cookie)).body;const invoice=state.invoices[0];assert.equal(invoice.total,99);assert.equal(state.discounts[0].used,1);
  await create('payments',{invoiceId:invoice.id,amount:40,method:'Card',date:today});
  assert.equal((await call('/records/payments','POST',{invoiceId:invoice.id,amount:60,method:'Card',date:today},cookie)).status,400);
  await create('payments',{invoiceId:invoice.id,amount:59,method:'Bank transfer',date:today});
  state=(await call('/state','GET',null,cookie)).body;assert.equal(state.invoices[0].status,'Paid');
  assert.equal((await call('/invoice-action','POST',{id:invoice.id,action:'cancel'},cookie)).status,400);
  assert.equal((await call(`/records/subscriptions/${sub.id}`,'PATCH',{unitPrice:100},cookie)).status,400);
  await create('subscriptions',{number:'SUB-OTHER',customerId:second.id,productId:product.id,planId:plan.id,quantity:1,unitPrice:50,starts:today,status:'Draft'});
  const customerPassword='Customer123';
  assert.equal((await call('/auth/register','POST',{name:'Customer One',email:'one@example.com',password:customerPassword})).status,200);
  const customerLogin=await call('/auth/login','POST',{email:'one@example.com',password:customerPassword});assert.equal(customerLogin.body.user.role,'customer');
  const beforeLink=(await call('/state','GET',null,customerLogin.cookie)).body;assert.equal(beforeLink.subscriptions.length,0,'Registering with a matching email must not claim existing customer contracts.');
  assert.equal((await call(`/records/customers/${customer.id}`,'PATCH',{email:'one@example.com'},cookie)).status,200);
  const own=(await call('/state','GET',null,customerLogin.cookie)).body;assert.equal(own.subscriptions.length,1);assert.equal(own.customers.every(c=>c.email==='one@example.com'),true);
  assert.equal((await call('/records/products','POST',{name:'Bad'},customerLogin.cookie)).status,403);
  const quote=await create('quotations',{number:'QUO-TEST',customerId:customer.id,productId:product.id,planId:plan.id,quantity:1,unitPrice:50,starts:today,ends:today,status:'Draft'});
  assert.equal((await call('/convert','POST',{id:quote.id},cookie)).status,200);
  assert.equal((await call('/convert','POST',{id:quote.id},cookie)).status,400);
  const staffPassword='Staffpass123';
  assert.equal((await call('/staff','POST',{name:'Staff',email:'staff@example.com',password:staffPassword},cookie)).status,200);
  const staff=await call('/auth/login','POST',{email:'staff@example.com',password:staffPassword});assert.equal(staff.body.user.role,'staff');
  assert.equal((await call('/records/taxes','POST',{name:'Forbidden',rate:50},staff.cookie)).status,403);
  assert.equal((await call('/staff','POST',{name:'Other',email:'other@example.com',password:staffPassword},staff.cookie)).status,403);
  assert.equal((await call('/auth/forgot','POST',{email:admin.email})).status,200);
  const token=output.match(/reset=([a-f0-9]+)/)?.[1];assert.ok(token);
  assert.equal((await call('/auth/reset','POST',{token:'invalid',password:'AnotherPass!43'})).status,400);
  assert.equal((await call('/auth/reset','POST',{token,password:'AnotherPass!43'})).status,200);
  assert.equal((await call('/state','GET',null,cookie)).status,401);
  assert.equal((await call('/auth/reset','POST',{token,password:'AnotherPass!44'})).status,400);
  assert.equal((await call('/auth/login','POST',admin)).status,401);
  const newLogin=await call('/auth/login','POST',{...admin,password:'AnotherPass!43'});assert.equal(newLogin.status,200);
  assert.equal((await call('/auth/logout','POST',{},newLogin.cookie)).status,200);
  assert.equal((await call('/state','GET',null,newLogin.cookie)).status,401);
});
